#!/usr/bin/env python3
"""Turn the built site (out/) into a Hostinger-ready folder (dist-hostinger/):
PHP admin + form endpoints, Cloudflare _headers/_redirects converted to .htaccess, PHP form endpoint added."""
import os, shutil, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT, DST, HS = os.path.join(ROOT, 'out'), os.path.join(ROOT, 'dist-hostinger'), os.path.join(ROOT, 'hostinger')
if not os.path.isdir(OUT): sys.exit('Run build/build.py first')
shutil.rmtree(DST, ignore_errors=True); shutil.copytree(OUT, DST)
for p in ('_headers', '_redirects'):
    q = os.path.join(DST, p); shutil.rmtree(q) if os.path.isdir(q) else (os.path.exists(q) and os.remove(q))
os.makedirs(os.path.join(DST, 'api'), exist_ok=True)
for f in os.listdir(os.path.join(HS, 'api')):
    if f.endswith('.php'): shutil.copy(os.path.join(HS, 'api', f), os.path.join(DST, 'api', f))

red = []
rp = os.path.join(OUT, '_redirects')
if os.path.exists(rp):
    for ln in open(rp, encoding='utf-8'):
        ln = ln.strip()
        if not ln or ln.startswith('#'): continue
        parts = ln.split()
        if len(parts) < 2: continue
        src, dst = parts[0], parts[1]; code = parts[2] if len(parts) > 2 else '301'
        if src.endswith('index.html') or '*' in src or ':' in src: continue   # would loop on Apache / not exact
        s = re.escape(src.rstrip('/')) or '/'
        red.append(f'RedirectMatch {code} ^{s}/?$ {dst}')

htaccess = f"""# Generated by build/hostinger.py - do not edit by hand
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset UTF-8
<IfModule mod_rewrite.c>
RewriteEngine On
RewriteCond %{{HTTPS}} !=on
RewriteCond %{{HTTP:X-Forwarded-Proto}} !https
RewriteRule ^ https://%{{HTTP_HOST}}%{{REQUEST_URI}} [L,R=301]
RewriteCond %{{HTTP:Authorization}} .
RewriteRule .* - [E=HTTP_AUTHORIZATION:%{{HTTP:Authorization}}]
RewriteRule ^api/lead/?$ /api/lead.php [L]
RewriteRule ^api/export/?$ /api/export.php [L]
RewriteRule ^api/img/([a-f0-9]{{24}})/?$ /api/img.php?id=$1 [L]
RewriteRule ^api/admin(?:/(.*))?$ /api/admin.php?path=$1 [L,QSA]
</IfModule>
<IfModule mod_headers.c>
Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"
Header always set X-Content-Type-Options "nosniff"
Header always set X-Frame-Options "DENY"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
Header always set Content-Security-Policy "default-src 'self'; script-src 'self' https://challenges.cloudflare.com https://www.googletagmanager.com; style-src 'self' https://fonts.googleapis.com; style-src-attr 'unsafe-inline'; font-src https://fonts.gstatic.com; img-src 'self' data: https://www.google-analytics.com; connect-src 'self' https://www.google-analytics.com https://*.analytics.google.com; frame-src https://challenges.cloudflare.com; form-action 'self'; base-uri 'self'; frame-ancestors 'none'"
</IfModule>
<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml text/plain text/xml
</IfModule>
<FilesMatch "^(gp-config|config|_core)\\.php$">
Require all denied
</FilesMatch>
{chr(10).join(red)}
"""
open(os.path.join(DST, '.htaccess'), 'w', encoding='utf-8').write(htaccess)
# Per-folder rules (Apache does not allow <Location> blocks in .htaccess files)
def sub(folder, body):
    os.makedirs(os.path.join(DST, folder), exist_ok=True)
    open(os.path.join(DST, folder, '.htaccess'), 'w', encoding='utf-8').write('<IfModule mod_headers.c>\n' + body + '</IfModule>\n')
long_cache = 'Header set Cache-Control "public, max-age=31536000, immutable"\n'
sub('assets', long_cache); sub('images', long_cache)
sub('admin', 'Header set X-Robots-Tag "noindex, nofollow"\nHeader set Cache-Control "no-store"\n')
sub('api', 'Header set Cache-Control "no-store"\n')
n = sum(len(f) for _, _, f in os.walk(DST))
print(f'dist-hostinger ready: {n} files, {len(red)} redirects')
